# --------------------------------------------------------------------------- #
# Random irregular geometry
# --------------------------------------------------------------------------- #
def _sample_polygon(rng: np.random.Generator) -> tuple[np.ndarray, float]:
    """Random irregular convex-ish polygon: center + jittered radial vertices."""
    cx, cy = rng.uniform(0.30, 0.70, size=2)
    rad = rng.uniform(*C.DATA.obstacle_radius_range)
    n_v = rng.integers(3, 10)  # 3..9 vertices -> irregular shapes
    ang = np.sort(rng.uniform(0.0, 2.0 * math.pi, size=n_v))
    # random radial jitter per vertex (irregularity)
    rj = rad * rng.uniform(0.55, 1.45, size=n_v)
    pts = np.stack([cx + rj * np.cos(ang), cy + rj * np.sin(ang)], axis=1)
    return pts, rad


def _winding_inside(px: np.ndarray, py: np.ndarray, poly: np.ndarray) -> np.ndarray:
    """Vectorized winding-number point-in-polygon test.

    px, py: [N] query coordinates; poly: [V, 2] polygon vertices (closed).
    Returns bool [N].
    """
    vx, vy = poly[:, 0], poly[:, 1]
    wx, wy = np.roll(vx, -1), np.roll(vy, -1)
    inside = np.zeros(px.shape, dtype=bool)
    for i in range(len(vx)):
        x1, y1, x2, y2 = vx[i], vy[i], wx[i], wy[i]
        cond = (y1 <= py) & (py < y2) | (y2 <= py) & (py < y1)
        with np.errstate(divide="ignore", invalid="ignore"):
            xint = x1 + (py - y1) * (x2 - x1) / (y2 - y1 + 1e-30)
        inside ^= cond & (px < xint)
    return inside


def _point_seg_dist(
    px: np.ndarray, py: np.ndarray, ax: float, ay: float, bx: float, by: float
) -> np.ndarray:
    """Distance from each query point to the segment (a, b). [N]"""
    abx, aby = bx - ax, by - ay
    denom = abx * abx + aby * aby + 1e-30
    t = np.clip(((px - ax) * abx + (py - ay) * aby) / denom, 0.0, 1.0)
    dx, dy = px - (ax + t * abx), py - (ay + t * aby)
    return np.sqrt(dx * dx + dy * dy)


def polygon_sdf(
    polys: list[np.ndarray], H: int, W: int
) -> tuple[np.ndarray, np.ndarray]:
    """Exact signed distance + masks on an H x W grid over the unit square.

    Returns (sdf, interior, ring):
      sdf      [H, W]  negative inside any polygon, positive outside (exact
                       Euclidean distance to polygon edges, via a 4x-finer
                       overlap grid + bilinear resampling for sub-cell edges)
      interior [H, W]  1.0 inside an obstacle
      ring     [H, W]  1.0 within +/- one cell of the boundary
    """
    ys = (np.arange(H) + 0.5) / H
    xs = (np.arange(W) + 0.5) / W
    gy, gx = np.meshgrid(ys, xs, indexing="ij")
    px, py = gx.ravel(), gy.ravel()

    # Evaluate on a 4x finer grid for sub-cell accuracy, then downsample.
    f = 4
    Hf, Wf = H * f, W * f
    ysf = (np.arange(Hf) + 0.5) / Hf
    xsf = (np.arange(Wf) + 0.5) / Wf
    gyf, gxf = np.meshgrid(ysf, xsf, indexing="ij")
    pxf, pyf = gxf.ravel(), gyf.ravel()

    inside_f = np.zeros(pxf.shape, dtype=bool)
    dist_f = np.full(pxf.shape, np.inf, dtype=np.float64)
    for poly in polys:
        inside_f ^= _winding_inside(pxf, pyf, poly)
        for i in range(len(poly)):
            ax, ay = poly[i]
            bx, by = poly[(i + 1) % len(poly)]
            dist_f = np.minimum(dist_f, _point_seg_dist(pxf, pyf, ax, ay, bx, by))
    sdf_f = np.where(inside_f, -dist_f, dist_f).reshape(Hf, Wf)

    # Bilinear downsample Hf x Wf -> H x W (average pooling by factor f).
    sdf = sdf_f.reshape(H, f, W, f).mean(axis=(1, 3))

    interior = (sdf < 0.0).astype(np.float64)
    step = 1.0 / H
    ring = (np.abs(sdf) <= 1.5 * step).astype(np.float64)
    return sdf.astype(np.float32), interior.astype(np.float32), ring.astype(np.float32)


# --------------------------------------------------------------------------- #
# Log-normal random permeability (smooth GRF via random Fourier features)
# --------------------------------------------------------------------------- #
def grf_field(rng: np.random.Generator, H: int, W: int) -> np.ndarray:
    """Smooth Gaussian random field with unit point variance on [0,1]^2."""
    M = C.DATA.n_random_fourier_modes
    kx = np.arange(-M // 2 + 1, M // 2 + 1)
    ky = np.arange(-M // 2 + 1, M // 2 + 1)
    KX, KY = np.meshgrid(kx, ky, indexing="ij")
    amp = np.exp(-2.5 * np.sqrt(KX**2 + KY**2))
    amp /= amp.sum() ** 0.5
    zr = rng.normal(size=KX.shape)
    zi = rng.normal(size=KX.shape)
    yy, xx = np.meshgrid(np.arange(H) / H, np.arange(W) / W, indexing="ij")
    a = np.zeros((H, W))
    for i in range(KX.shape[0]):
        for j in range(KX.shape[1]):
            if amp[i, j] < 1e-12:
                continue
            phase = 2 * math.pi * (KX[i, j] * xx + KY[i, j] * yy)
            a += amp[i, j] * (
                zr[i, j] * np.cos(phase) - zi[i, j] * np.sin(phase)
            )
    a -= a.mean()
    a /= a.std() + 1e-8
    return a


# --------------------------------------------------------------------------- #
# Batched Darcy solver (GPU): PCG with multigrid-preconditioned CG
# --------------------------------------------------------------------------- #
def _build_K(a: torch.Tensor, interior: torch.Tensor) -> torch.Tensor:
    """Permeability K on the grid: [B, 1, H, W]. Sealed frame + obstacle walls."""
    K_eps = C.DATA.eps
    s = C.DATA.lognormal_scale
    K = torch.exp(s * a) + K_eps
    # Outer frame: seal with tiny K (periodic box with an interior wall).
    K[:, :, :2, :] = K_eps
    K[:, :, -2:, :] = K_eps
    K[:, :, :, :2] = K_eps
    K[:, :, :, -2:] = K_eps
    # Obstacle interiors: tiny K (flow cannot cross the rock).
    K = K * (1.0 - interior) + K_eps * interior
    return K


def _lap(K: torch.Tensor, u: torch.Tensor) -> torch.Tensor:
    """The operator A u = -div(K grad u) on a periodic grid (SPD, up to null
    space when unshifted); K, u: [B, 1, H, W].

    Face conductivities, forward differences, and divergence by differencing
    the incoming/outgoing face fluxes. Sign convention: POSITIVE operator, so
    that A + penalty*I is SPD and conjugate gradients apply directly.
    """
    Kx_p = 0.5 * (K[:, :, :, 1:] + K[:, :, :, :-1])  # face conductivities
    Ky_p = 0.5 * (K[:, :, 1:, :] + K[:, :, :-1, :])
    fx = Kx_p * (u[:, :, :, 1:] - u[:, :, :, :-1])  # flux across x-faces
    fy = Ky_p * (u[:, :, 1:, :] - u[:, :, :-1, :])
    fx = torch.nn.functional.pad(fx, (0, 1, 0, 0))
    fy = torch.nn.functional.pad(fy, (0, 0, 0, 1))
    # -div(K grad u): incoming minus outgoing face flux per cell
    return (
        torch.roll(fx, 1, dims=-1) - fx + torch.roll(fy, 1, dims=-2) - fy
    )


def _face_conductivities(K: torch.Tensor):
    Kx = 0.5 * (K[:, :, :, 1:] + K[:, :, :, :-1])
    Ky = 0.5 * (K[:, :, 1:, :] + K[:, :, :-1, :])
    return Kx, Ky


def _diag(K: torch.Tensor, penalty: float) -> torch.Tensor:
    """Exact diagonal of the shifted operator L + penalty*I (Jacobi)."""
    Kx, Ky = _face_conductivities(K)
    dx = torch.nn.functional.pad(Kx, (1, 0)) + torch.nn.functional.pad(Kx, (0, 1))
    dy = torch.nn.functional.pad(Ky, (0, 0, 1, 0)) + torch.nn.functional.pad(
        Ky, (0, 0, 0, 1)
    )
    return dx + dy + penalty


def _smooth(
    K: torch.Tensor,
    rhs: torch.Tensor,
    u: torch.Tensor,
    iters: int,
    penalty: float,
    omega: float = 0.8,
) -> torch.Tensor:
    """Damped Jacobi smoothing of the shifted system (L + p I) u = rhs.

    Uses the exact operator diagonal (sum of face conductances), which is
    required for stability with strongly heterogeneous permeability.
    """
    d = _diag(K, penalty).clamp_min(1e-12)
    for _ in range(iters):
        Au = _lap(K, u) + penalty * u
        u = u + omega * (rhs - Au) / d
    return u


def _restrict(x: torch.Tensor) -> torch.Tensor:
    # 2x2 average pooling restriction
    B, C, H, W = x.shape
    return x.reshape(B, C, H // 2, 2, W // 2, 2).mean(dim=(3, 5))


def _prolong(x: torch.Tensor, H: int, W: int) -> torch.Tensor:
    return torch.nn.functional.interpolate(
        x, size=(H, W), mode="bilinear", align_corners=False
    )


def _mg_vcycle(
    K: torch.Tensor,
    rhs: torch.Tensor,
    u: torch.Tensor,
    penalty: float,
    depth: int = 3,
) -> torch.Tensor:
    """One V-cycle of batched geometric multigrid (Jacobi smoother)."""
    H, W = u.shape[-2:]
    if min(H, W) <= 4 or depth == 0:
        return _smooth(K, rhs, u, iters=8, penalty=penalty)
    u = _smooth(K, rhs, u, iters=2, penalty=penalty)
    res = rhs - (_lap(K, u) + penalty * u)
    Kc = _restrict(K).clamp_min(C.DATA.eps)
    rc = _restrict(res)
    uc = torch.zeros_like(rc)
    uc = _mg_vcycle(Kc, rc, uc, penalty, depth - 1)
    u = u + _prolong(uc, H, W)
    u = _smooth(K, rhs, u, iters=2, penalty=penalty)
    return u


def solve_darcy_batch(
    a: torch.Tensor,
    interior: torch.Tensor | None,
    tol: float = 1e-6,
    max_iter: int = 400,
    piecewise_K: torch.Tensor | None = None,
    use_obstacle_sinks: bool = True,
) -> torch.Tensor:
    """Solve the batched Darcy system with penalty BCs. Returns u [B, 1, H, W].

    The true operator is

        A u = -div(K grad u) + penalty * sink * u,
        sink = obstacle interior | outer frame (2-cell border),

    i.e. homogeneous Dirichlet conditions on obstacle walls *and* on the
    sealed outer frame (the classic Darcy benchmark scaling, u = O(0.1)),
    enforced with PCG. The preconditioner is one multigrid V-cycle on the
    *shifted* system (L + penalty I) -- SPD, data-independent, and a classic
    shifted-Laplacian preconditioner (Erlangga et al.), which keeps CG valid.

    ``piecewise_K`` (optional) supplies the permeability grid directly (the
    canonical piecewise-constant Darcy benchmark); otherwise K is built from
    the log-normal field + obstacle masks via ``_build_K``.

    ``use_obstacle_sinks=False`` solves the plain benchmark -- flow passes
    through high-permeability regions, with sinks only on the outer frame
    (no Dirichlet walls inside the domain).

    a, interior: [B, 1, H, W] on the target device.
    """
    if piecewise_K is not None:
        K = piecewise_K.clone()
        K_eps = C.DATA.eps
        K[:, :, :2, :] = K_eps
        K[:, :, -2:, :] = K_eps
        K[:, :, :, :2] = K_eps
        K[:, :, :, -2:] = K_eps
        sink_source = interior
    else:
        K = _build_K(a, interior)
        sink_source = interior
    Kmax = K.amax(dim=(2, 3), keepdim=True)
    penalty = 3e3 * Kmax

    _, _, H, W = a.shape
    frame = torch.zeros_like(sink_source)
    frame[:, :, :2, :] = 1.0
    frame[:, :, -2:, :] = 1.0
    frame[:, :, :, :2] = 1.0
    frame[:, :, :, -2:] = 1.0
    if use_obstacle_sinks:
        sink = (sink_source + frame).clamp(0.0, 1.0)
    else:
        sink = frame

    # Source: unit forcing in the conductive region, zero on sinks. The h2
    # factor is the finite-volume cell measure: the flux-balance form of the
    # discrete equation is  sum_f K (u_n - u_c) = f * h^2,  which yields the
    # classic benchmark scaling u = O(0.1) independent of resolution
    # (crucial for consistent 48 -> 96 super-resolution).
    h2 = 1.0 / (H * W)
    rhs = h2 * (1.0 - sink)

    def Aop(x):
        return _lap(K, x) + penalty * sink * x

    # Initial guess: smooth bubble (helps PCG converge fast).
    yy = torch.linspace(0, 1, H, device=a.device).view(H, 1)
    xx = torch.linspace(0, 1, W, device=a.device).view(1, W)
    bubble = (yy * (1 - yy)) * (xx * (1 - xx))
    u = (0.1 * bubble).expand_as(a).contiguous()

    b_norm = rhs.norm(dim=(2, 3), keepdim=True).clamp_min(1e-12)
    r = rhs - Aop(u)
    z = _mg_vcycle(K, r, torch.zeros_like(r), penalty)
    p = z.clone()
    rz = (r * z).sum(dim=(2, 3), keepdim=True)
    for _ in range(max_iter):
        Ap = Aop(p)
        pAp = (p * Ap).sum(dim=(2, 3), keepdim=True).clamp_min(1e-30)
        alpha = rz / pAp
        u = u + alpha * p
        r = r - alpha * Ap
        res_rel = (r.norm(dim=(2, 3), keepdim=True) / b_norm).max()
        if res_rel < tol:
            break
        z = _mg_vcycle(K, r, torch.zeros_like(r), penalty)
        rz_new = (r * z).sum(dim=(2, 3), keepdim=True)
        beta = rz_new / rz.clamp_min(1e-30)
        p = z + beta * p
        rz = rz_new
    return u


# --------------------------------------------------------------------------- #
# Canonical piecewise-constant Darcy benchmark (Li et al. 2021 family)
# --------------------------------------------------------------------------- #
def circles_sdf(
    centers: list[tuple[float, float]],
    radii: list[float],
    H: int,
    W: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Exact signed distance to circle boundaries on an H x W grid.

    The signed distance to a union of circles is computed analytically
    (|x - c| - r per circle, sign from the inside test) -- exact and fast.
    Returns (sdf, interior, ring) with the same conventions as
    ``polygon_sdf``: negative inside any circle, ring = within 1.5 cells of
    a boundary.
    """
    ys = (np.arange(H) + 0.5) / H
    xs = (np.arange(W) + 0.5) / W
    gy, gx = np.meshgrid(ys, xs, indexing="ij")
    px, py = gx.ravel(), gy.ravel()
    dist = np.full(px.shape, np.inf, dtype=np.float64)
    inside = np.zeros(px.shape, dtype=bool)
    for (cx, cy), r in zip(centers, radii):
        d = np.sqrt((px - cx) ** 2 + (py - cy) ** 2) - r
        dist = np.minimum(dist, np.abs(d))
        inside |= d < 0.0
    sdf = np.where(inside, -dist, dist).reshape(H, W)
    interior = (sdf < 0.0).astype(np.float32)
    step = 1.0 / H
    ring = (np.abs(sdf) <= 1.5 * step).astype(np.float32)
    return sdf.astype(np.float32), interior, ring


def make_split_piecewise(split: str, n: int, res: int, device: str = "cpu") -> dict:
    """Canonical Darcy benchmark data: piecewise-constant permeability.

    The unit square is split into ``n_squares x n_squares`` equal cells; each
    cell contains one circle with a random center/radius. K = k_high inside
    any circle and k_low outside (the FNO paper setting, K in {1, 12}). The
    solution is the plain benchmark: -div(K grad u) = f, u = 0 on the outer
    frame, flow passes through the circles (no interior walls).

    Output keys match ``make_split``: a (K field), u, sdf, interior, ring.
    """
    split_off = int(hashlib.md5(split.encode()).hexdigest(), 16) % (2**31)
    rng = np.random.default_rng(C.SEED + split_off)
    cfg = C.DATA
    n_sq = cfg.pw_n_squares
    ys = (np.arange(res) + 0.5) / res
    xs = (np.arange(res) + 0.5) / res
    gy, gx = np.meshgrid(ys, xs, indexing="ij")
    samples = []
    bs = 64
    for i0 in range(0, n, bs):
        nb = min(bs, n - i0)
        a_b, sdf_b, interior_b, ring_b = [], [], [], []
        for _ in range(nb):
            centers, radii = [], []
            K = np.full((res, res), cfg.pw_k_low, dtype=np.float64)
            for i in range(n_sq):
                for j in range(n_sq):
                    cx = (i + rng.uniform(0.25, 0.75)) / n_sq
                    cy = (j + rng.uniform(0.25, 0.75)) / n_sq
                    r = rng.uniform(*cfg.pw_radius_range)
                    centers.append((cx, cy))
                    radii.append(r)
                    mask = (gx - cx) ** 2 + (gy - cy) ** 2 <= r * r
                    K[mask] = cfg.pw_k_high
            sdf, interior, ring = circles_sdf(centers, radii, res, res)
            a_b.append(K)
            sdf_b.append(sdf)
            interior_b.append(interior)
            ring_b.append(ring)
        a = torch.tensor(np.stack(a_b), dtype=torch.float32)[:, None].to(device)
        sdf_t = torch.tensor(np.stack(sdf_b), dtype=torch.float32)[:, None].to(device)
        interior = torch.tensor(np.stack(interior_b), dtype=torch.float32)[:, None].to(device)
        ring = torch.tensor(np.stack(ring_b), dtype=torch.float32)[:, None].to(device)
        u = solve_darcy_batch(
            a, interior, piecewise_K=a, use_obstacle_sinks=False
        )
        samples.append(
            dict(
                a=a.cpu().numpy(),
                u=u.cpu().numpy(),
                sdf=sdf_t.cpu().numpy(),
                interior=interior.cpu().numpy(),
                ring=ring.cpu().numpy(),
            )
        )
    out = {k: np.concatenate([s[k] for s in samples], axis=0) for k in samples[0]}
    out["meta"] = dict(
        split=split, n=n, res=res, seed=C.SEED, kind="piecewise",
        config=asdict(C.DATA),
    )
    return out


# --------------------------------------------------------------------------- #
# Sample generation
# --------------------------------------------------------------------------- #
def make_split(split: str, n: int, res: int, device: str = "cpu") -> dict:
    """Generate one data split end-to-end on `device` (batched on GPU)."""
    # Stable, process-independent split offset (Python's hash() is salted).
    split_off = int(hashlib.md5(split.encode()).hexdigest(), 16) % (2**31)
    rng = np.random.default_rng(C.SEED + split_off)
    samples = []
    bs = 64
    for i0 in range(0, n, bs):
        nb = min(bs, n - i0)
        a_b, sdf_b, interior_b, ring_b = [], [], [], []
        for _ in range(nb):
            polys = []
            n_obs = int(rng.integers(C.DATA.n_obstacles_range[0], C.DATA.n_obstacles_range[1] + 1))
            for _ in range(n_obs):
                poly, _rad = _sample_polygon(rng)
                polys.append(poly)
            sdf, interior, ring = polygon_sdf(polys, res, res)
            sdf_b.append(sdf)
            interior_b.append(interior)
            ring_b.append(ring)
            a_b.append(grf_field(rng, res, res))
        a = torch.tensor(np.stack(a_b), dtype=torch.float32)[:, None]
        sdf_t = torch.tensor(np.stack(sdf_b), dtype=torch.float32)[:, None]
        interior = torch.tensor(np.stack(interior_b), dtype=torch.float32)[:, None]
        ring = torch.tensor(np.stack(ring_b), dtype=torch.float32)[:, None]
        a, sdf_t, interior = a.to(device), sdf_t.to(device), interior.to(device)
        ring = ring.to(device)
        u = solve_darcy_batch(a, interior)
        samples.append(
            dict(
                a=a.cpu().numpy(),
                u=u.cpu().numpy(),
                sdf=sdf_t.cpu().numpy(),
                interior=interior.cpu().numpy(),
                ring=ring.cpu().numpy(),
            )
        )
    out = {
        k: np.concatenate([s[k] for s in samples], axis=0) for k in samples[0]
    }
    out["meta"] = dict(split=split, n=n, res=res, seed=C.SEED,
                       config=asdict(C.DATA))
    return out


def normalize_split(train: dict, other: dict) -> tuple[dict, dict, dict]:
    """Compute normalization stats from the training split, apply to both."""
    a_mu, a_sd = train["a"].mean(), train["a"].std() + 1e-8
    u_mu, u_sd = train["u"].mean(), train["u"].std() + 1e-8
    train_n = dict(train)
    other_n = dict(other)
    for d in (train_n, other_n):
        d["a"] = (d["a"] - a_mu) / a_sd
        d["u"] = (d["u"] - u_mu) / u_sd
    stats = dict(
        a_mu=float(a_mu), a_sd=float(a_sd), u_mu=float(u_mu), u_sd=float(u_sd)
    )
    return train_n, other_n, stats


