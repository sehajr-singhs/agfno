def volume_path(vol_root: str, fname: str) -> str:
    d = os.path.join(vol_root, "data")
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, fname)


def load_or_make_split(
    split: str,
    n: int,
    res: int,
    vol_root: str,
    device: str = "cpu",
    kind: str = "obstacles",
) -> dict:
    """Load a cached split from the Modal volume or generate + cache it."""
    import glob as _glob

    fname = C.DATA.shard_name(split, n, res, kind)
    path = volume_path(vol_root, fname)
