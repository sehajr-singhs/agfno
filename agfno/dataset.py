# PDE family 2: advection-diffusion past fixed-temperature obstacles
# --------------------------------------------------------------------------- #
def sample_velocity(rng: np.random.Generator, res: int) -> tuple[np.ndarray, np.ndarray]:
    """Divergence-free velocity field v = curl(psi), psi a smooth random field.

    v = (dpsi/dy, -dpsi/dx) is EXACTLY divergence-free on the periodic grid
    (central differences), so the advected scalar conserves its spatial
    integral in the absence of diffusion -- a physical sanity check (test).
    Returns (vx, vy), each [res, res] with RMS = C.ADVEC.vel_rms.
    """
    A = C.ADVEC
    M = A.psi_modes
    yy, xx = np.meshgrid(np.arange(res) / res, np.arange(res) / res, indexing="ij")
    psi = np.zeros((res, res))
    for _ in range(8):  # superpose a few random spectral modes
        kx = int(rng.integers(-M, M + 1))
        ky = int(rng.integers(-M, M + 1))
        if kx == 0 and ky == 0:
            continue
        amp = rng.normal() / (1.0 + (kx**2 + ky**2) ** 0.75)
        ph = 2 * math.pi * rng.uniform(0, 1)
        psi += amp * np.cos(2 * math.pi * (kx * xx + ky * yy) + ph)
    psi -= psi.mean()
    # central-difference curl on the periodic grid
    vx = (np.roll(psi, -1, axis=0) - np.roll(psi, 1, axis=0)) / 2.0 * res
    vy = -(np.roll(psi, -1, axis=1) - np.roll(psi, 1, axis=1)) / 2.0 * res
    s = A.vel_rms / (np.sqrt((vx**2 + vy**2).mean()) + 1e-12)
    return vx * s, vy * s


def _semi_lagrangian_advect(
    u: torch.Tensor, vx: torch.Tensor, vy: torch.Tensor, dt: float
) -> torch.Tensor:
    """Backward semi-Lagrangian advection step (unconditionally stable).

    u_new(x) = u(x - v dt), sampled bilinearly. Backtraces can leave the box
    by up to one CFL cell; we use reflection padding (smooth, standard in
    weather-emulation nets) -- the velocity field itself is periodic and
    localized hot spots carry vanishing mass at the boundary.
    vx, vy: [B, 1, H, W] in domain units (RMS ~ C.ADVEC.vel_rms).
    """
    B, _, H, W = u.shape
    yy, xx = torch.meshgrid(
        torch.arange(H, device=u.device, dtype=u.dtype),
        torch.arange(W, device=u.device, dtype=u.dtype),
        indexing="ij",
    )
    # backtrace
    sx = xx[None, None] - vx * dt * H  # vx in [0,1]^2 units -> cells = *H
    sy = yy[None, None] - vy * dt * H
    # normalize to [-1, 1] grid_sample coordinates (align_corners=True so
    # integer indices map exactly onto pixel centers); grid: [B, H, W, 2]
    gx = 2.0 * sx / (W - 1) - 1.0
    gy = 2.0 * sy / (H - 1) - 1.0
    grid = torch.stack([gx.squeeze(1), gy.squeeze(1)], dim=-1)  # [B, H, W, 2]
    return torch.nn.functional.grid_sample(
        u, grid, mode="bilinear", padding_mode="reflection", align_corners=True
    )


def _advec_diffusion_solve(
    u: torch.Tensor, nu: float, dt: float, interior: torch.Tensor, tol: float = 1e-8
) -> torch.Tensor:
    """Implicit diffusion step: (I + dt*nu*L + penalty*M) u_new = u_adv.

    L is the positive periodic Laplacian (_lap with K = 1); M = obstacle
    interior mask with a strong penalty enforcing u = 0 (ambient) inside
    obstacles. SPD system -> multigrid-preconditioned PCG (reuses the Darcy
    machinery with a constant-coefficient operator).
    """
    B, _, H, W = u.shape
    ones = torch.ones_like(u)
    penalty = 3e3  # >> 1/(dt*nu): obstacle cells pinned to ~0
    K = ones  # constant coefficient

    def Aop(x):
        return x + dt * nu * _lap(K, x) + penalty * interior * x

    d = _diag(ones, penalty * interior + 1.0).clamp_min(1e-12)
    rhs = u_adv = u  # unpreconditioned system: A u_new = u_adv

    # PCG with one Jacobi-smoothed V-cycle as preconditioner (no multigrid
    # restriction needed: constant coefficient, few iterations suffice)
    b_norm = rhs.norm(dim=(2, 3), keepdim=True).clamp_min(1e-12)
    x = u_adv / (1.0 + dt * nu * (2.0 / H**2 + 2.0 / W**2) + penalty * interior)  # diag precond guess
    r = rhs - Aop(x)
    z = r / d
    p = z
    rz = (r * z).sum(dim=(2, 3), keepdim=True)
    for _ in range(60):
        Ap = Aop(p)
        pAp = (p * Ap).sum(dim=(2, 3), keepdim=True).clamp_min(1e-30)
        alpha = rz / pAp
        x = x + alpha * p
        r = r - alpha * Ap
        if (r.norm(dim=(2, 3), keepdim=True) / b_norm).max() < tol:
            break
        z = r / d
        rz_new = (r * z).sum(dim=(2, 3), keepdim=True)
        p = z + (rz_new / rz.clamp_min(1e-30)) * p
        rz = rz_new
    return x


def make_advec_split(
    split: str, n: int, res: int, device: str = "cpu"
) -> dict:
    """Generate one advection-diffusion split on `device` (batched on GPU).

    Returns dict with:
      a       [n, 1, H, W]  initial scalar field u(t=0) (raw, positive bumps)
      v       [n, 2, H, W]  steady divergence-free velocity (raw units)
      u_T     [n, 1, H, W]  ground-truth u after n_steps_train steps
      u_long  [n, 1, H, W]  ground truth after n_steps_long steps (zero-shot)
      sdf / interior / ring as in the Darcy splits
    """
    A = C.ADVEC
    split_off = int(hashlib.md5(("advec-" + split).encode()).hexdigest(), 16) % (2**31)
    rng = np.random.default_rng(C.SEED + 7777 + split_off)
    samples = []
    bs = 64
    for i0 in range(0, n, bs):
        nb = min(bs, n - i0)
        a_b, v_b, sdf_b, int_b, ring_b = [], [], [], [], []
        for _ in range(nb):
            polys = []
            n_obs = int(rng.integers(C.DATA.n_obstacles_range[0], C.DATA.n_obstacles_range[1] + 1))
            for _ in range(n_obs):
                poly, _rad = _sample_polygon(rng)
                polys.append(poly)
            sdf, interior, ring = polygon_sdf(polys, res, res)
            sdf_b.append(sdf)
            int_b.append(interior)
            ring_b.append(ring)
            # initial condition: positive hot spots, zeroed inside obstacles
            u0 = np.zeros((res, res), dtype=np.float64)
            n_b = int(rng.integers(A.n_bumps_range[0], A.n_bumps_range[1] + 1))
            yy, xx = np.meshgrid(np.arange(res) / res, np.arange(res) / res, indexing="ij")
            for _ in range(n_b):
                cx, cy = rng.uniform(0.15, 0.85, size=2)
                sg = rng.uniform(*A.bump_sigma_range)
                amp = rng.uniform(*A.bump_amp_range)
                u0 += amp * np.exp(-(((xx - cx) ** 2 + (yy - cy) ** 2) / (2 * sg**2)))
            # keep temperature ambient inside obstacles (walls are cold)
            u0[interior > 0.5] = 0.0
            a_b.append(u0)
            vx, vy = sample_velocity(rng, res)
            v_b.append(np.stack([vx, vy]))
        a = torch.tensor(np.stack(a_b), dtype=torch.float32)[:, None].to(device)
        v = torch.tensor(np.stack(v_b), dtype=torch.float32).to(device)
        interior = torch.tensor(np.stack(int_b), dtype=torch.float32)[:, None].to(device)
        sdf_t = torch.tensor(np.stack(sdf_b), dtype=torch.float32)[:, None].to(device)
        ring = torch.tensor(np.stack(ring_b), dtype=torch.float32)[:, None].to(device)

        # time integration (shared across the batch)
        u = a
        for _ in range(A.n_steps_train):
            u = _semi_lagrangian_advect(u, v[:, 0:1], v[:, 1:2], A.dt)
            u = _advec_diffusion_solve(u, A.nu, A.dt, interior)
        u_T = u
        for _ in range(A.n_steps_long - A.n_steps_train):
            u = _semi_lagrangian_advect(u, v[:, 0:1], v[:, 1:2], A.dt)
            u = _advec_diffusion_solve(u, A.nu, A.dt, interior)
        u_long = u

        samples.append(
            dict(
                a=a.cpu().numpy(),
                v=v.cpu().numpy(),
                u_T=u_T.cpu().numpy(),
                u_long=u_long.cpu().numpy(),
                sdf=sdf_t.cpu().numpy(),
                interior=interior.cpu().numpy(),
                ring=ring.cpu().numpy(),
            )
        )
    out = {k: np.concatenate([s[k] for s in samples], axis=0) for k in samples[0]}
    out["meta"] = dict(split=split, n=n, res=res, seed=C.SEED, family="advec",
                       config=asdict(A))
    return out
