"""Dataset: 2-D Darcy flow with irregular polygonal obstacles.

Physics
-------
We solve the variable-coefficient elliptic PDE

    -div( K(x, y) grad u(x, y) ) = f(x, y)      in  Omega = unit square
    u = 0                        on obstacle walls and the sealed outer frame
                                 (2-cell border with K = K_eps; sets the
                                 pressure scale and keeps the FFT box valid)

with a smooth log-normal heterogeneous permeability

    K(x) = K_eps + exp( s * a(x) ),   a = smooth Gaussian random field,

and f = 1 (the classic Li et al. Darcy benchmark setting). Obstacles are
random irregular polygons (3-9 vertices, random sizes/rotations); on their
boundary we impose homogeneous Dirichlet conditions with a *smooth*
penalty/immersion approach that keeps the discrete operator symmetric and
its action exactly batched on GPU:

    A u = -div( K grad u ) + penalty * r(x) * u,   r = 1 inside obstacles,

which converges (as penalty -> infinity) to the constrained solution and
avoids staircasing artifacts of naive masking. We use penalty = 3e3 * K_max,
validated against a reference high-accuracy solve (see tests).

Numerics
--------
* finite differences, 5-point Laplacian, cell-centered uniform grid,
* the outer frame (2 cells) is sealed with K = K_eps AND carries homogeneous
  Dirichlet conditions, giving the classic benchmark scaling (u = O(0.1)) and
  a strictly SPD discrete problem (no pure-Neumann null space),
* solve with Conjugate Gradient preconditioned with one V(1,1)-cycle of a
  GPU-batched geometric multigrid smoother; batched over the whole split,
* ground truth is therefore *not* generated by FNO-style pseudo-solvers but
  by a real iterative PDE solver with residual stopping criterion.

Geometry
--------
The SDF is exact (negative inside the obstacle, positive outside) and is
computed with a vectorized winding-number point-in-polygon test + dense
point-to-segment distances. It is resampled from a fine overlap grid
(fine_res >= 2 x data res) so boundaries stay sharp at any resolution --
the same signed distance is evaluated at 48 or 96 directly.
"""

from __future__ import annotations

import hashlib
import math
import os
